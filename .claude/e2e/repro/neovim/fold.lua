local function closed(l) return vim.fn.foldclosed(l) end
local function has(p) return vim.iter(lines()):any(function(l) return l:find(p) end) end

H.section('cycling, ellipsis, startup, visibility, blank lines', function()
  H.open(dir .. '/c.org', { 'intro line', '* A', '** A1', 'text', '- item', '  - sub', '** A2', '', '', '* B', 'b text' })
  wait('folds', function() return vim.fn.foldlevel(2) > 0 end)
  vim.api.nvim_win_set_cursor(0, { 2, 0 })
  press('<Tab>')
  eq(closed(2), 2, 'folded')
  local ft = vim.api.nvim_win_call(0, function() vim.v.foldstart = 2 return require('org-lsp.folds').foldtext() end)
  eq(ft[#ft][1], ' ▾', 'org_ellipsis shown after the folded headline')
  H.out('  folded A ends at ' .. vim.fn.foldclosedend(2) .. ' (two blank lines before * B should stay visible: 7)')
  check(vim.fn.foldclosedend(2) <= 7, 'two blank lines after a subtree stay visible')
  press('<Tab>')
  eq({ closed(2), closed(3), closed(7) }, { -1, 3, 7 }, 'children shown, folded')
  H.out('  list folded at children state: ' .. closed(5))
  press('<Tab>')
  eq(closed(3), -1, 'subtree')
  -- S-Tab
  press('<S-Tab>')
  eq({ closed(2), closed(10) }, { 2, 10 }, 'overview')
  press('<S-Tab>')
  eq({ closed(2), closed(10) }, { -1, -1 }, 'everything')
  -- TAB at bob with org_cycle_global_at_bob
  vim.api.nvim_win_set_cursor(0, { 1, 0 })
  press('<Tab>')
  H.sleep(300)
  H.out('  TAB at bob: closed(2)=' .. closed(2) .. ' closed(10)=' .. closed(10))
  check(closed(2) == 2 and closed(10) == 10, 'TAB at the start of a file cycles globally')
  press('<S-Tab>')
  -- startup content and visibility
  H.open(dir .. '/s.org', { '#+STARTUP: content', '* A', ':PROPERTIES:', ':VISIBILITY: children', ':END:', '** A1', 'a1 text', '* B', ':PROPERTIES:', ':VISIBILITY: all', ':END:', '** B1', 'b1 text', '* C', 'c text' })
  wait('startup folds', function() return closed(14) == 14 end)
  H.out('  startup content: ' .. vim.inspect({ closed(3), closed(6), closed(9), closed(12), closed(14) }))
  check(closed(6) == 6, 'VISIBILITY children: A1 folded')
  check(closed(12) == -1, 'VISIBILITY all: B1 open')
  H.open(dir .. '/o.org', { '#+STARTUP: overview', '* A', 'text', '* B', 'text' })
  wait('overview', function() return closed(2) == 2 and closed(4) == 4 end)
  -- TAB on a new heading
  H.open(dir .. '/n.org', { '* A', '** ', '- a', '- ' })
  vim.api.nvim_win_set_cursor(0, { 2, 2 })
  press('<Tab>')
  wait('** -> *', function() return line(2) == '* ' end)
  press('<Tab>')
  wait('* -> **', function() return line(2) == '** ' end)
  vim.api.nvim_win_set_cursor(0, { 4, 1 })
  press('<Tab>')
  wait('item indented', function() return line(4) == '  - ' end)
end)

H.section('narrow, archived folded, sparse, reveal', function()
  H.open(dir .. '/w.org', { '* A', 'a text', '** A1', '* B', '** Old :ARCHIVE:', 'old text', '** New', '* TODO C', 'apple pie', '* D', '** E', '*** F', 'deep apple' })
  vim.api.nvim_win_set_cursor(0, { 1, 0 })
  local org = vim.api.nvim_get_current_buf()
  press('<Leader>ons')
  wait('narrowed file', function() return vim.api.nvim_get_current_buf() ~= org end)
  H.out('  narrowed: ' .. vim.api.nvim_buf_get_name(0) .. ' ' .. vim.inspect(lines()))
  vim.api.nvim_buf_set_lines(0, 1, 2, false, { 'a text changed' })
  vim.cmd('write')
  wait('written back', function() return H.lines(org)[2] == 'a text changed' end)
  check(not vim.bo[org].modified, 'the Org file saved')
  press('<Leader>onw')
  wait('widened', function() return vim.api.nvim_get_current_buf() == org end)
  -- archived subtree stays folded
  vim.api.nvim_win_set_cursor(0, { 4, 0 })
  press('<Tab>')
  press('<Tab>')
  H.sleep(200)
  H.out('  B children: closed(5)=' .. closed(5) .. ' closed(7)=' .. closed(7))
  press('<Tab>')
  H.sleep(200)
  eq(closed(5), 5, 'ARCHIVE subtree stays folded when the parent opens')
  -- sparse tree of TODOs
  H.keys({ 't' })
  press('<Leader>o/')
  H.sleep(1000)
  H.out('  sparse: ' .. vim.inspect({ closed(1), closed(4), closed(8), closed(10) }))
  local ns = vim.api.nvim_create_namespace('org_lsp_sparse')
  local marks = vim.api.nvim_buf_get_extmarks(0, ns, 0, -1, {})
  check(#marks > 0, 'TODO highlighted')
  check(closed(8) == -1 or closed(8) ~= 8, 'TODO C visible')
  press('x')
  H.sleep(300)
  check(#vim.api.nvim_buf_get_extmarks(0, ns, 0, -1, {}) == 0, 'typing takes the highlights away')
  press('u')
  -- reveal
  press('zM')
  vim.api.nvim_win_set_cursor(0, { 13, 0 })
  press('<Leader>oR')
  H.sleep(800)
  H.out('  reveal: ' .. vim.inspect({ closed(10), closed(11), closed(12), closed(13), closed(1), closed(4) }))
  check(closed(13) == -1 and closed(1) == 1, 'reveal opens the headlines above and leaves others folded')
end)

H.section('indent, hidestars, adapt, =, num', function()
  H.open(dir .. '/i.org', { '#+STARTUP: indent hidestars num', '* A', 'text a', '** B', 'text b' })
  H.sleep(800)
  local marks = vim.api.nvim_buf_get_extmarks(0, -1, 0, -1, { details = true })
  local shown = {}
  for _, m in ipairs(marks) do
    if m[4].virt_text then table.insert(shown, m[2] .. ':' .. vim.inspect(vim.tbl_map(function(c) return c[1] end, m[4].virt_text))) end
  end
  H.out('  virt text: ' .. vim.inspect(shown))
  check(vim.iter(shown):any(function(s) return s:find('^2:') end), 'text indented by level (virtual)')
  check(vim.iter(shown):any(function(s) return s:find('1%.1') end), '#+STARTUP: num shows 1.1')
  eq(lines(), { '#+STARTUP: indent hidestars num', '* A', 'text a', '** B', 'text b' }, 'the file unchanged')
  vim.cmd('Org num mode')
  H.sleep(600)
  local m2 = vim.api.nvim_buf_get_extmarks(0, -1, 0, -1, { details = true })
  local any = vim.iter(m2):any(function(m) return m[4].virt_text and vim.iter(m[4].virt_text):any(function(c) return c[1]:find('1%.1') end) end)
  check(not any, ':Org num mode turns the numbers off')
  -- = re-indent
  H.open(dir .. '/r.org', { '* A', '      text', '- item', 'cont' })
  press('gg=G')
  H.sleep(800)
  H.out('  after =: ' .. vim.inspect(lines()))
end)

