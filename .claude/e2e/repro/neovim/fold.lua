H.section('diagnostics', function()
  H.open(dir .. '/d.org', { '* A', 'text ** heading', '[[file:nowhere.org]] [[*No heading]]', '#+begin_src python :foo 1', 'x = 1', '#+end_src', '#+begin_quote', 'open' })
  H.sleep(1500)
  local d = vim.diagnostic.get(0)
  H.out('  diagnostics: ' .. vim.inspect(vim.tbl_map(function(x) return { x.lnum, x.severity, x.message } end, d)))
  check(vim.iter(d):all(function(x) return x.severity >= vim.diagnostic.severity.INFO end), 'only information or hints')
  check(vim.iter(d):any(function(x) return x.lnum == 1 end), 'heading in a paragraph')
  check(vim.iter(d):any(function(x) return x.message:find(':foo') end), 'unknown header argument')
  check(vim.iter(d):any(function(x) return x.message:lower():find('block') end), 'block left open')
  check(not vim.iter(d):any(function(x) return x.message:find('nowhere') end), 'link-to-local-file ignored')
end)

H.section('citations', function()
  H.open(dir .. '/ci.org', { '* A', 'See [cite:@knuth84] and [cite:@knut].', '' })
  local c = H.client()
  H.sleep(800)
  local r = c:request_sync('textDocument/hover', { textDocument = { uri = vim.uri_from_bufnr(0) }, position = { line = 1, character = 13 } }, 3000, 0)
  H.out('  hover cite: ' .. vim.inspect(r and r.result and r.result.contents))
  check(r and r.result ~= nil, 'hover shows the entry')
  local d = vim.diagnostic.get(0)
  H.out('  diags: ' .. vim.inspect(vim.tbl_map(function(x) return x.message end, d)))
  check(vim.iter(d):any(function(x) return x.message:find('knut') end), 'unknown key reported')
  vim.api.nvim_buf_set_lines(0, 2, 3, false, { '[cite:@' })
  H.sleep(500)
  local cr = c:request_sync('textDocument/completion', { textDocument = { uri = vim.uri_from_bufnr(0) }, position = { line = 2, character = 7 } }, 3000, 0)
  local items = cr and cr.result and (cr.result.items or cr.result) or {}
  H.out('  cite completion: ' .. vim.inspect(vim.tbl_map(function(i) return i.label end, items)))
  check(#items >= 2, 'keys completed')
  vim.api.nvim_buf_set_lines(0, 2, 3, false, { '' })
  vim.api.nvim_win_set_cursor(0, { 3, 0 })
  H.selects({ 'knuth74', 'knuth74' })
  H.inputs({ 'knuth74' })
  H.keys({ '\r' })
  press('<Leader>oic')
  H.sleep(2000)
  H.out('  inserted cite: ' .. vim.inspect(lines()) .. ' asked ' .. vim.inspect(H.select_asked[#H.select_asked]) .. vim.inspect(H.inputs_asked[#H.inputs_asked]))
end)

