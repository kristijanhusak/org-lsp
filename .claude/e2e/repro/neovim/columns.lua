-- Column view in an Org file and in the agenda (Emacs): e on an effort.
local H = dofile('/home/user/org-lsp/.claude/e2e/repro/neovim/h.lua')
local dir = H.tmpdir('columns')
H.init({ settings = { org_agenda_files = { dir }, clock = { today = '2026-10-21', now = '10:30' } } })
local function columns_on() return vim.b.org_lsp_columns ~= nil or #vim.api.nvim_buf_get_extmarks(0, -1, 0, -1, { details = true }) > 0 end
H.section('file column view edit', function()
  local f = dir .. '/tasks.org'
  H.open(f, { '#+COLUMNS: %25ITEM %TODO %Effort{:}', '* TODO Write', ':PROPERTIES:', ':Effort: 1:00', ':END:', '* TODO Read', ':PROPERTIES:', ':Effort: 0:30', ':END:' })
  vim.api.nvim_win_set_cursor(0, { 2, 0 })
  local n = #H.notes
  H.press('<Leader>oxc')
  H.sleep(6000)
  H.out('  after oxc notes: ' .. vim.inspect(H.notes_since(n)) .. ' column=' .. tostring(require('org-lsp.columns').column(0)))
  H.press('l'); H.press('l')
  H.out('  column now ' .. tostring(require('org-lsp.columns').column(0)))
  H.inputs({ '2:00' })
  H.press('e')
  H.sleep(6000)
  H.out('  asked: ' .. vim.inspect(H.inputs_asked[#H.inputs_asked]) .. ' notes ' .. vim.inspect(H.notes_since(n)))
  H.eq(H.line(4), ':EFFORT:   2:00', 'effort edited in column view (as Emacs writes it)')
  H.press('q')
  H.sleep(1000)
end)
H.section('agenda column view edit', function()
  local n = #H.notes
  if os.getenv('WIPE') then
    vim.cmd('silent! write')
    vim.cmd('enew')
    vim.cmd('bwipeout! ' .. vim.fn.bufnr(dir .. '/tasks.org'))
    H.sleep(500)
  end
  H.keys({ 't' })
  H.press('<Leader>oa')
  H.wait('todo list', function() return vim.bo.filetype == 'org-agenda' and H.line(1):find('Global') end)
  H.press('<C-c><C-x><C-c>')
  H.sleep(6000)
  vim.api.nvim_win_set_cursor(0, { 2, 0 })
  H.press('l'); H.press('l')
  H.inputs({ '0:45' })
  H.press('e')
  H.sleep(6000)
  H.out('  asked: ' .. vim.inspect(H.inputs_asked[#H.inputs_asked]) .. ' notes ' .. vim.inspect(H.notes_since(n)))
  local fb = vim.fn.bufnr(dir .. '/tasks.org')
  H.out('  file: ' .. vim.inspect(fb > 0 and H.lines(fb) or {}) .. ' disk ' .. vim.inspect(vim.fn.readfile(dir .. '/tasks.org')))
  H.check(vim.iter(vim.fn.readfile(dir .. '/tasks.org')):any(function(l) return l:find('0:45') end), 'effort edited from agenda column view')
end)
H.done()
