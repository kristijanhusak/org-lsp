local H = dofile('/home/user/org-lsp/.claude/e2e/repro/neovim/h.lua')
local dir = H.tmpdir('columns2')
vim.fn.writefile({ '#+COLUMNS: %40ITEM %TODO %Effort{:}', '* Projects', '** TODO [#A] Write report :urgent:', 'SCHEDULED: <2026-10-21 Wed 09:00>', ':PROPERTIES:', ':Effort: 1:00', ':END:', '** TODO Call the client', 'DEADLINE: <2026-10-23 Fri>', ':PROPERTIES:', ':Effort: 0:20', ':END:' }, dir .. '/work.org')
H.init({ settings = { org_agenda_files = { dir }, clock = { today = '2026-10-21', now = '10:30' } } })
H.section('week agenda column edit', function()
  local n = #H.notes
  H.keys({ 'a' })
  H.press('<Leader>oa')
  H.wait('week', function() return vim.bo.filetype == 'org-agenda' and H.line(1):find('Week') end)
  H.press('<C-c><C-x><C-c>')
  H.sleep(6000)
  H.out(table.concat(H.lines(), '\n'))
  for i, l in ipairs(H.lines()) do if l:find('Write report') then vim.api.nvim_win_set_cursor(0, { i, 0 }) end end
  H.out('  on line ' .. H.cursor()[1])
  H.press('l'); H.press('l')
  H.out('  column ' .. tostring(require('org-lsp.columns').column(0)))
  H.inputs({ '2:00' })
  H.press('e')
  H.sleep(6000)
  H.out('  asked: ' .. vim.inspect(H.inputs_asked[#H.inputs_asked]) .. ' notes ' .. vim.inspect(H.notes_since(n)))
  H.out('  disk ' .. vim.inspect(vim.fn.readfile(dir .. '/work.org')))
end)
H.done()
