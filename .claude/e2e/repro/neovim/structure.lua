H.section('todo file keywords', function()
  H.open(dir .. '/t2.org', { '#+TODO: TODO | DONE', '#+TODO: REPORT BUG | FIXED', '* REPORT x' })
  vim.api.nvim_win_set_cursor(0, { 3, 0 })
  local seq = {}
  for _ = 1, 4 do
    local before = line(3)
    press('cit')
    H.wait(nil, function() return line(3) ~= before end)
    table.insert(seq, line(3))
  end
  eq(seq, { '* BUG x', '* FIXED x', '* x', '* REPORT x' }, 'cycling within the set: BUG FIXED none REPORT')
  local n = #H.notes
  vim.api.nvim_win_set_cursor(0, { 3, 0 })
  vim.cmd('Org todo nextset')
  H.sleep(400)
  H.out('  nextset: ' .. vim.inspect(H.notes_since(n)) .. ' line ' .. line(3))
  check(H.note_seen('Keyword-Set', n), 'Keyword-Set message')
  vim.cmd('Org todo previousset')
  H.sleep(400)
  H.out('  previousset: ' .. vim.inspect(H.notes_since(n)) .. ' line ' .. line(3))
  H.open(dir .. '/t3.org', { '#+TODO: A B | C', '* A x' })
  vim.api.nvim_win_set_cursor(0, { 2, 0 })
  press('cit')
  H.wait(nil, function() return line(2) ~= '* A x' end)
  H.out('  #+TODO: A B | C cit -> ' .. line(2) .. ' prompts ' .. vim.inspect(H.key_prompts[#H.key_prompts]))
  eq(line(2), '* B x', 'file keywords used')
end)

