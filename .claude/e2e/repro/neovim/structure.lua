H.section('inline task', function()
  H.open(dir .. '/i.org', { '* A', 'text' })
  vim.api.nvim_win_set_cursor(0, { 2, 0 })
  press('<Leader>oiI')
  wait('an inline task', function() return vim.iter(lines()):any(function(l) return l:match('^%*%*%*%*%*%*%*%*%*%*%*%*%*%*%* ') end) end)
  H.out('  inline task: ' .. vim.inspect(lines()))
  vim.cmd('stopinsert')
  local row
  for i, l in ipairs(lines()) do
    if l:match('^%*%*%*%*%*%*%*%*%*%*%*%*%*%*%* ') then row = i end
  end
  check(vim.iter(lines()):any(function(l) return l == '*************** END' end), 'an END line')
  if row then
    vim.api.nvim_win_set_cursor(0, { row, 0 })
    press('>>')
    wait('both demoted', function()
      return line(row):match('^%*%*%*%*%*%*%*%*%*%*%*%*%*%*%*%* ') and vim.iter(lines()):any(function(l) return l == '**************** END' end)
    end)
  end
  local c = H.client()
  local syms = c:request_sync('textDocument/documentSymbol', { textDocument = vim.lsp.util.make_text_document_params(0) }, 2000, 0).result
  eq(#syms, 1, 'the outline has only * A')
  eq(syms[1].children == nil or #syms[1].children == 0, true, 'and leaves the inline task out')
end)

H.section('cut/copy/paste subtree', function()
  H.open(dir .. '/c.org', { '* A', 'a text', '* B', '** B1' })
  vim.api.nvim_win_set_cursor(0, { 1, 0 })
  local n = #H.notes
  press('<Leader>osd')
  all_become({ '* B', '** B1' }, 'cut the subtree')
  eq(vim.fn.getreg('"'), '* A\na text\n', 'cut goes to the register')
  H.out('  cut msg: ' .. vim.inspect(H.notes_since(n)))
  vim.api.nvim_win_set_cursor(0, { 2, 0 })
  press('<Leader>osp')
  wait('pasted', function() return #lines() == 4 end)
  H.out('  pasted on ** B1: ' .. vim.inspect(lines()))
  check(vim.tbl_contains(lines(), '*** A') or vim.tbl_contains(lines(), '** A'), 'pasted at a level that fits')
  H.out('  paste msg: ' .. vim.inspect(H.notes_since(n)))
  -- copy a folded subtree
  H.open(dir .. '/c2.org', { '* A', 'a text', '* B' })
  vim.api.nvim_win_set_cursor(0, { 1, 0 })
  wait('folds', function() return vim.fn.foldlevel(1) > 0 end)
  press('<Tab>')
  eq(vim.fn.foldclosed(1), 1, 'A folded')
  press('<Leader>osy')
  H.sleep(200)
  vim.api.nvim_win_set_cursor(0, { 3, 0 })
  press('<Leader>osp')
  wait('pasted copy', function() return #lines() == 5 end)
  H.out('  copy+paste: ' .. vim.inspect(lines()))
  local copy_row
  for i = 3, #lines() do
    if line(i) == '* A' then copy_row = i end
  end
  check(copy_row and H.wait(nil, function() return vim.fn.foldclosed(copy_row) == copy_row end), 'the pasted copy is folded too')
end)

