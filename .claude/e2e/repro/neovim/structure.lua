local eq, check, press, line, lines, wait = H.eq, H.check, H.press, H.line, H.lines, H.wait

local function becomes(n, text, msg)
  return wait(msg .. ': ' .. text, function()
    return line(n) == text
  end)
end
local function all_become(expected, msg)
  local ok = H.wait(nil, function()
    return vim.deep_equal(lines(), expected)
  end)
  return eq(lines(), expected, msg)
end

