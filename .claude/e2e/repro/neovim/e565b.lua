local H = dofile('/home/user/org-lsp/.claude/e2e/repro/neovim/h.lua')
local dir = H.tmpdir('e565')
H.init({ settings = { clock = { today = '2026-10-21', now = '12:44' } } })
local function cal() return H.calendar_win() ~= nil and vim.api.nvim_get_current_win() == H.calendar_win() and vim.api.nvim_get_mode().mode == 'n' end
H.section('e565', function()
  H.open(dir .. '/t.org', { '* A', 'x' })
  vim.api.nvim_win_set_cursor(0, { 2, 0 })
  H.press('<Leader>oi.')
  H.wait('cal', cal)
  H.press('l')
  H.press('<CR>')
  H.wait('range?', function() return H.line(2):find('<2026') end)
  H.out('A ' .. #H.errors_in_messages() .. ' ' .. H.line(2))
  H.press('o<Esc>')
  H.out('B ' .. #H.errors_in_messages())
  H.sleep(1000)
  H.out('C ' .. #H.errors_in_messages() .. ' ' .. vim.inspect(H.lines()))
end)
H.done()
