local H = dofile('/home/user/org-lsp/.claude/e2e/repro/neovim/h.lua')
local dir = H.tmpdir('cmdcomp')
H.init({ settings = {} })
H.section('Org completion', function()
  H.open(dir .. '/a.org', { '* A' })
  H.out('  "Org ag": ' .. vim.inspect(vim.list_slice(vim.fn.getcompletion('Org ag', 'cmdline'), 1, 8)))
  H.out('  "Org agenda ": ' .. vim.inspect(vim.list_slice(vim.fn.getcompletion('Org agenda ', 'cmdline'), 1, 8)))
  H.out('  "Org agenda l": ' .. vim.inspect(vim.list_slice(vim.fn.getcompletion('Org agenda l', 'cmdline'), 1, 8)))
  H.out('  "Org schedule ": ' .. vim.inspect(vim.list_slice(vim.fn.getcompletion('Org schedule ', 'cmdline'), 1, 8)))
  local n = #H.notes
  vim.cmd('Org agenda.list')
  H.sleep(800)
  H.out('  :Org agenda.list -> ft ' .. vim.bo.filetype .. ' notes ' .. vim.inspect(H.notes_since(n)))
  vim.cmd('Org nosuch command')
  H.sleep(800)
  H.out('  :Org nosuch command -> notes ' .. vim.inspect(H.notes_since(n)))
end)
H.done()
