local H = dofile('/home/user/org-lsp/.claude/e2e/repro/neovim/h.lua')
local dir = H.tmpdir('heads')
H.init({ settings = { clock = { today = '2026-10-21', now = '10:30' } } })
local press, line, lines, wait = H.press, H.line, H.lines, H.wait
H.section('emacs heading commands', function()
  H.open(dir .. '/h.org', { '* A', 'plain', '* B', '* C' })
  vim.api.nvim_win_set_cursor(0, { 2, 0 })
  vim.cmd('Org toggle heading')
  wait('line made heading', function() return line(2):find('^%*+ plain') end, 20000)
  H.out('  toggle heading: ' .. line(2))
  vim.cmd('Org toggle heading')
  wait('and back', function() return line(2) == 'plain' end, 20000)
  vim.api.nvim_win_set_cursor(0, { 3, 0 })
  press('<Leader>o;')
  wait('COMMENT', function() return line(3) == '* COMMENT B' end, 20000)
  press('<Leader>o;')
  wait('COMMENT off', function() return line(3) == '* B' end, 20000)
  -- selection: two headlines demoted together
  vim.api.nvim_win_set_cursor(0, { 3, 0 })
  press('Vj>>')
  wait('both demoted', function() return line(3) == '** B' and line(4) == '** C' end, 10000)
  H.out('  after V>>: ' .. vim.inspect(lines()))
  -- selection: lines turned into headings
  H.open(dir .. '/s.org', { '* T', 'one', 'two' })
  vim.api.nvim_win_set_cursor(0, { 2, 0 })
  vim.api.nvim_feedkeys(vim.keycode('Vj'), 'nx', false)
  H.plugin.run('org.toggle.heading', { region = true })
  wait('lines made headings', function() return line(2):find('^%*') and line(3):find('^%*') end, 20000)
  H.out('  region toggle heading: ' .. vim.inspect(lines()))
  -- clone
  H.open(dir .. '/c.org', { '* Meet <2026-10-21 Wed>', 'notes', '* After' })
  vim.api.nvim_win_set_cursor(0, { 1, 0 })
  H.inputs({ '2', '+1w' })
  press('<Leader>osc')
  wait('cloned', function() return #lines() >= 7 end, 20000)
  H.out('  clone: ' .. vim.inspect(lines()) .. ' asked ' .. vim.inspect(vim.list_slice(H.inputs_asked, #H.inputs_asked - 1)))
  -- org.outline.path, open line
  local n = #H.notes
  vim.cmd('Org outline path')
  H.sleep(800)
  H.out('  outline path: ' .. vim.inspect(H.notes_since(n)))
end)
H.done()
