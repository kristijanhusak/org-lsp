-- Minimal: the date prompt and :redraw in headless nightly with 140x50.
local H = dofile('/home/user/org-lsp/.claude/e2e/repro/neovim/h.lua')
local dir = H.tmpdir('crash')
vim.o.lines = tonumber(os.getenv('L') or '50')
vim.o.columns = tonumber(os.getenv('C') or '140')
H.init({ settings = { clock = { today = '2026-10-21', now = '10:30' } } })
H.section('crash', function()
  H.open(dir .. '/a.org', { '* A' })
  H.press('<Leader>ois')
  H.wait('calendar', function() return H.calendar_win() ~= nil end)
  io.stderr:write('before redraw\n')
  vim.cmd.redraw()
  io.stderr:write('after redraw\n')
  vim.api.nvim_win_set_cursor(H.calendar_win(), { 7, 46 })
  vim.api.nvim_win_call(H.calendar_win(), function() vim.cmd('normal! zz') end)
  vim.cmd.redraw()
  io.stderr:write('after zz redraw\n')
end)
H.done()
