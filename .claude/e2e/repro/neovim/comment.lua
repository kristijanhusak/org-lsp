local H = dofile('/home/user/org-lsp/.claude/e2e/repro/neovim/h.lua')
local dir = H.tmpdir('comment')
H.init({ settings = {} })
H.section('comment cursor', function()
  H.open(dir .. '/h.org', { '* A', 'plain', '* B', '* C' })
  vim.api.nvim_win_set_cursor(0, { 3, 0 })
  H.press('<Leader>o;')
  H.wait('COMMENT', function() return H.line(3) == '* COMMENT B' end, 20000)
  H.out('  cursor after o; ' .. vim.inspect(H.cursor()))
  H.press('<Leader>o;')
  H.sleep(3000)
  H.out('  after second o; ' .. vim.inspect(H.lines()) .. ' cursor ' .. vim.inspect(H.cursor()))
  vim.api.nvim_win_set_cursor(0, { 2, 3 })
  vim.cmd('Org toggle heading')
  H.wait('heading', function() return H.line(2):find('^%*') end, 20000)
  H.sleep(500)
  H.out('  cursor after toggle heading ' .. vim.inspect(H.cursor()) .. ' ' .. H.line(2))
  vim.api.nvim_win_set_cursor(0, { 4, 0 })
  H.press('<Leader>osc')
  H.sleep(3000)
  H.out('  cursor after clone ' .. vim.inspect(H.cursor()) .. ' ' .. vim.inspect(H.lines()))
end)
H.done()
