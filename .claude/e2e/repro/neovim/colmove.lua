local H = dofile('/home/user/org-lsp/.claude/e2e/repro/neovim/h.lua')
local dir = H.tmpdir('colmove')
H.init({ settings = {} })
H.section('column follows', function()
  H.open(dir .. '/c.org', { '#+COLUMNS: %25ITEM %TODO %Effort %Size', '* TODO A', ':PROPERTIES:', ':Effort: 1:00', ':Size: S', ':END:' })
  vim.api.nvim_win_set_cursor(0, { 2, 0 })
  H.press('<Leader>oxc'); H.sleep(6000)
  local cols = require('org-lsp.columns')
  H.press('lll')
  H.out('  picked ' .. cols.column(0))
  H.press('<M-Left>'); H.sleep(4000)
  H.out('  after M-Left: ' .. H.line(1) .. ' picked ' .. cols.column(0))
  H.eq(cols.column(0), 2, 'the picked column follows the column moved left (Emacs: backward-char after the swap)')
  local n = #H.notes
  H.press('<M-Down>'); H.sleep(4000)
  H.out('  M-Down: ' .. vim.inspect(H.notes_since(n)))
end)
H.done()
