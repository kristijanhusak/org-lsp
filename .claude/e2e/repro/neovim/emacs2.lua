-- More Emacs-backed checks: slow block with typing, formula and field
-- editing, detangle, Library of Babel, export template/stack, Markdown via
-- emacs_config.
local H = dofile('/home/user/org-lsp/.claude/e2e/repro/neovim/h.lua')
local dir = H.tmpdir('emacs2')
H.init({ settings = { emacs_config = "(setq org-export-backends '(ascii html icalendar latex odt md))", emacs_options = { ['org-confirm-babel-evaluate'] = false } } })
local press, line, lines, wait, check = H.press, H.line, H.lines, H.wait, H.check
local function has(p, b) return vim.iter(H.lines(b)):any(function(l) return l:find(p) end) end

H.section('slow block, typing meanwhile', function()
  H.open(dir .. '/s.org', { '#+begin_src emacs-lisp', '(progn (sleep-for 4) 42)', '#+end_src', '', 'text' })
  vim.api.nvim_win_set_cursor(0, { 2, 0 })
  local n = #H.notes
  press('<Leader>obe')
  H.sleep(1500)
  vim.api.nvim_buf_set_lines(0, 4, 5, false, { 'typed while running' })
  H.sleep(6000)
  H.out('  slow block: ' .. vim.inspect(lines()) .. ' notes ' .. vim.inspect(H.notes_since(n)))
  check(not has('^: 42'), 'results dropped')
  check(#H.notes_since(n) > 0, 'with a warning')
end)

H.section('formula and field editing', function()
  H.open(dir .. '/f.org', { '| 1 | 2 |   |', '#+TBLFM: $3=$1+$2' })
  vim.api.nvim_win_set_cursor(0, { 1, 2 })
  press("<Leader>o'")
  wait('formula buffer', function() return vim.api.nvim_buf_get_name(0) ~= vim.fs.normalize(dir .. '/f.org') end, 20000)
  H.out('  formulas buffer: ' .. vim.api.nvim_buf_get_name(0) .. ' ' .. vim.inspect(lines()))
  for i, l in ipairs(lines()) do
    if l:find('%$3') then vim.api.nvim_buf_set_lines(0, i - 1, i, false, { (l:gsub('%$1%+%$2', '$1*$2')) }) end
  end
  vim.cmd('write')
  wait('TBLFM written', function() return has('#%+TBLFM: %$3=%$1%*%$2', vim.fn.bufnr(dir .. '/f.org')) end, 20000)
  vim.cmd('buffer ' .. vim.fn.bufnr(dir .. '/f.org'))
  H.sleep(1000)
  vim.api.nvim_win_set_cursor(0, { 1, 2 })
  press('<Leader>o`')
  wait('field buffer', function() return vim.api.nvim_buf_get_name(0) ~= vim.fs.normalize(dir .. '/f.org') end, 20000)
  H.out('  field buffer: ' .. vim.inspect(lines()))
  vim.api.nvim_buf_set_lines(0, 0, -1, false, { 'long', 'value' })
  vim.cmd('write')
  wait('field written back on one line', function() return has('^| long value', vim.fn.bufnr(dir .. '/f.org')) end, 20000)
  H.out('  table: ' .. vim.inspect(H.lines(vim.fn.bufnr(dir .. '/f.org'))))
end)

H.section('detangle, lob', function()
  H.open(dir .. '/t.org', { '#+NAME: double', '#+begin_src emacs-lisp :tangle out.el :comments link :var x=2', '(* x 2)', '#+end_src' })
  press('<Leader>obt')
  wait('tangled', function() return vim.fn.filereadable(dir .. '/out.el') == 1 end, 20000)
  local t = vim.fn.readfile(dir .. '/out.el')
  for i, l in ipairs(t) do if l:find('%(%* x 2%)') then t[i] = '(* x 3)' end end
  vim.fn.writefile(t, dir .. '/out.el')
  H.inputs({ dir .. '/out.el' })
  press('<Leader>obd')
  wait('detangled', function() return has('^%(%* x 3%)') end, 20000)
  local n = #H.notes
  press('<Leader>obi')
  H.wait(nil, function() return #H.notes > n end, 20000)
  H.out('  ingest: ' .. vim.inspect(H.notes_since(n)))
  H.open(dir .. '/call.org', { '#+CALL: double(x=5)', '' })
  vim.api.nvim_win_set_cursor(0, { 1, 0 })
  press('<Leader>obe')
  wait('call result', function() return has('^: 10') or has('^: 15') end, 20000)
  H.out('  call: ' .. vim.inspect(lines()))
end)

H.section('export menu: markdown, template, stack', function()
  H.open(dir .. '/x.org', { '#+TITLE: X', '* One', 'text' })
  H.keys({ 'q' })
  press('<Leader>oe')
  H.sleep(6000)
  local menu = H.key_prompts[#H.key_prompts]
  H.out('  menu: ' .. vim.inspect(menu and menu.choices))
  check(menu and vim.iter(menu.choices):any(function(c) return c:find('Markdown') end), 'Markdown from emacs_config in the menu')
  H.keys({ 'm', 'm' })
  press('<Leader>oe')
  wait('md written', function() return vim.fn.filereadable(dir .. '/x.md') == 1 end, 30000)
  H.keys({ '#' })
  H.selects({ 'default' })
  H.inputs({ 'default' })
  vim.api.nvim_win_set_cursor(0, { 3, 0 })
  press('<Leader>oe')
  H.sleep(6000)
  H.out('  after #: ' .. vim.inspect(lines()) .. ' asked ' .. vim.inspect(H.select_asked[#H.select_asked]) .. vim.inspect(H.inputs_asked[#H.inputs_asked]))
  check(has('^#%+OPTIONS:'), 'options template inserted')
  H.keys({ '&' })
  H.selects({ 1 })
  press('<Leader>oe')
  H.sleep(5000)
  H.out('  stack asked: ' .. vim.inspect(H.select_asked[#H.select_asked]) .. ' key ' .. vim.inspect(H.key_prompts[#H.key_prompts]) .. ' buf ' .. vim.api.nvim_buf_get_name(0))
end)

H.done()
