local H = dofile('/home/user/org-lsp/.claude/e2e/repro/neovim/h.lua')
local dir = H.tmpdir('detangle')
H.init({ settings = {} })
H.section('detangle', function()
  H.open(dir .. '/t.org', { '#+begin_src emacs-lisp :tangle out.el :comments link', '(* 2 2)', '#+end_src' })
  H.press('<Leader>obt')
  H.wait('tangled', function() return vim.fn.filereadable(dir .. '/out.el') == 1 end, 20000)
  local t = vim.fn.readfile(dir .. '/out.el')
  H.out('  out.el: ' .. vim.inspect(t))
  for i, l in ipairs(t) do if l == '(* 2 2)' then t[i] = '(* 3 3)' end end
  vim.fn.writefile(t, dir .. '/out.el')
  local n = #H.notes
  H.inputs({ dir .. '/out.el' })
  H.press('<Leader>obd')
  H.sleep(6000)
  H.out('  after obd: buffer ' .. vim.inspect(H.lines()) .. ' disk ' .. vim.inspect(vim.fn.readfile(dir .. '/t.org')) .. ' asked ' .. vim.inspect(H.inputs_asked[#H.inputs_asked]) .. ' notes ' .. vim.inspect(H.notes_since(n)))
end)
H.done()
