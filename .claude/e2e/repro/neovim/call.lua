local H = dofile('/home/user/org-lsp/.claude/e2e/repro/neovim/h.lua')
local dir = H.tmpdir('call')
H.init({ settings = { emacs_options = { ['org-confirm-babel-evaluate'] = false } } })
H.section('call', function()
  H.open(dir .. '/t.org', { '#+NAME: double', '#+begin_src emacs-lisp :tangle out.el :comments link :var x=2', '(* x 3)', '#+end_src' })
  local n = #H.notes
  H.press('<Leader>obi')
  H.wait(nil, function() return #H.notes > n end, 20000)
  H.out('  ingest: ' .. vim.inspect(H.notes_since(n)))
  H.open(dir .. '/call.org', { '#+CALL: double(x=5)', '' })
  vim.api.nvim_win_set_cursor(0, { 1, 0 })
  H.press('<Leader>obe')
  H.wait('result', function() return vim.iter(H.lines()):any(function(l) return l:find('^: %d') end) end, 20000)
  H.out('  call (other file): ' .. vim.inspect(H.lines()))
  H.open(dir .. '/t.org')
  vim.api.nvim_buf_set_lines(0, -1, -1, false, { '', '#+CALL: double(x=5)' })
  vim.api.nvim_win_set_cursor(0, { 6, 0 })
  H.press('<Leader>obe')
  H.wait('result same file', function() return vim.iter(H.lines()):any(function(l) return l:find('^: %d') end) end, 20000)
  H.out('  call (same file): ' .. vim.inspect(H.lines()))
end)
H.done()
