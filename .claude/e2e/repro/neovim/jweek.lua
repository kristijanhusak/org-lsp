local H = dofile('/home/user/org-lsp/.claude/e2e/repro/neovim/h.lua')
local base = H.tmpdir('jweek')
vim.fn.mkdir(base .. '/j', 'p')
vim.fn.writefile({ '* Tuesday, 10/20/26', '** TODO carried' }, base .. '/j/20261020')
H.init({ settings = { clock = { today = '2026-10-21', now = '10:30' }, org_journal_enabled = true, org_journal_dir = base .. '/j', calendar_week_start_day = tonumber(os.getenv('WS') or '0') } })
H.section('week', function()
  H.open(base .. '/x.org', { '* x' })
  for _, period in ipairs({ 'w', 'm', 'y' }) do
    vim.cmd('Org journal new date entry')
    H.wait('calendar', function() return H.calendar_win() ~= nil and vim.api.nvim_get_current_win() == H.calendar_win() end)
    H.press('l')
    H.sleep(500)
    H.inputs({ 'carried' })
    H.press('<Leader>js' .. period)
    H.wait('results', function() return vim.api.nvim_buf_get_name(0):find('search') end)
    H.out('  ' .. period .. ' (cursor on Thu 10/22): ' .. H.line(1))
    H.sleep(500)
  end
end)
H.done()
