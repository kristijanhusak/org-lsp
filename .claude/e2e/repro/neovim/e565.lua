local H = dofile('/home/user/org-lsp/.claude/e2e/repro/neovim/h.lua')
local dir = H.tmpdir('e565')
H.init({ settings = { clock = { today = '2026-10-21', now = '12:44' } } })
local function step(name, fn) fn(); H.sleep(800); local bad = H.errors_in_messages(); H.out(name .. ': ' .. #bad .. ' ' .. vim.inspect(H.lines()) .. ' ft=' .. vim.bo.filetype) end
H.section('e565', function()
  H.open(dir .. '/t.org', { '* A', 'x' })
  step('A space then oi.', function() vim.api.nvim_win_set_cursor(0, { 2, 0 }); H.press('A <Esc>'); vim.api.nvim_win_set_cursor(0, { 2, 1 }); H.press('<Leader>oi.') end)
  step('CR', function() H.press('<CR>') end)
  step('empty line oi!', function() vim.api.nvim_win_set_cursor(0, { 2, 0 }); H.press('o<Esc>'); H.press('<Leader>oi!') end)
  step('CR', function() H.press('<CR>') end)
  step('oi. on x', function() vim.api.nvim_win_set_cursor(0, { 2, 0 }); H.press('<Leader>oi.') end)
  step('CR', function() H.press('<CR>') end)
  step('oi. again (range)', function() H.press('<Leader>oi.') end)
  step('l CR', function() H.press('l'); H.press('<CR>') end)
end)
H.done()
