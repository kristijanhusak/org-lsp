local H = dofile('/home/user/org-lsp/.claude/e2e/repro/neovim/h.lua')
local dir = H.tmpdir('crypt')
H.init({ settings = { emacs_config = '(require (quote org-crypt)) (setq org-crypt-key "tester@example.org") (setq epg-pinentry-mode (quote loopback)) (org-crypt-use-before-save-magic)', org_tags_exclude_from_inheritance = { 'crypt' } } })
H.section('crypt', function()
  H.open(dir .. '/c.org', { '* Secret :crypt:', 'hidden text', '* Other :crypt:', 'more text' })
  local n = #H.notes
  vim.cmd('Org crypt encrypt')
  H.wait('encrypted', function() return vim.iter(H.lines()):any(function(l) return l:find('BEGIN PGP MESSAGE') end) end, 30000)
  H.out('  after encrypt: ' .. vim.inspect(vim.list_slice(H.lines(), 1, 4)) .. ' notes ' .. vim.inspect(H.notes_since(n)))
  vim.cmd('Org crypt decrypt')
  H.wait('decrypted', function() return H.line(2) == 'hidden text' end, 30000)
  vim.cmd('Org crypt encrypt all')
  H.wait('all encrypted', function()
    local c = 0
    for _, l in ipairs(H.lines()) do if l:find('BEGIN PGP MESSAGE') then c = c + 1 end end
    return c == 2
  end, 30000)
  vim.cmd('Org crypt decrypt all')
  H.wait('all decrypted', function() return not vim.iter(H.lines()):any(function(l) return l:find('PGP') end) end, 30000)
  vim.cmd('write')
  H.sleep(4000)
  local disk = vim.fn.readfile(dir .. '/c.org')
  H.out('  disk after save: ' .. vim.inspect(vim.list_slice(disk, 1, 4)) .. ' buffer ' .. vim.inspect(vim.list_slice(H.lines(), 1, 3)) .. ' notes ' .. vim.inspect(H.notes_since(n)))
  H.check(vim.iter(disk):any(function(l) return l:find('BEGIN PGP MESSAGE') end), 'saving encrypts the crypt entries (before-save magic)')
end)
H.done()
