-- TESTING.org: Tables, Table formulas, Code blocks, Export, Attachments,
-- Timers, with `emacs_options` from the Lua config (org-attach-method mv,
-- org-export-with-toc false).
local H = dofile('/home/user/org-lsp/.claude/e2e/repro/neovim/h.lua')
local dir = H.tmpdir('emacs')
H.init({
  settings = {
    clock = { today = '2026-10-21', now = '10:30' },
    emacs_options = { ['org-attach-method'] = 'mv', ['org-export-with-toc'] = false, ['org-confirm-babel-evaluate'] = true },
  },
})
local eq, check, press, line, lines, wait = H.eq, H.check, H.press, H.line, H.lines, H.wait
local function has(p, buf) return vim.iter(H.lines(buf)):any(function(l) return l:find(p) end) end

H.section('tables', function()
  H.open(dir .. '/t.org', { '| a | bb |', '|---+----|', '| 1 | 2 |', '| 3 | 4 |', '', 'x' })
  vim.lsp.buf.format({ async = false })
  H.sleep(300)
  eq(vim.list_slice(lines(), 1, 4), { '| a | bb |', '|---+----|', '| 1 |  2 |', '| 3 |  4 |' }, 'format aligns the table (numbers right, as Org)')
  vim.api.nvim_win_set_cursor(0, { 3, 2 })
  vim.cmd('Org table next field')
  H.wait(nil, function() return H.cursor()[2] == 6 end, 2000)
  eq(H.cursor(), { 3, 6 }, 'next field')
  vim.cmd('Org table previous field')
  H.wait(nil, function() return H.cursor()[2] == 2 end, 2000)
  vim.api.nvim_win_set_cursor(0, { 4, 6 })
  vim.cmd('Org table next field')
  wait('row made after last field', function() return #lines() == 7 and line(5):find('^|%s+|%s+|$') end)
  H.out('  after next field past end: ' .. vim.inspect(lines()))
  -- move column, row
  vim.api.nvim_win_set_cursor(0, { 3, 2 })
  press('>>')
  wait('column moved right', function() return line(1):find('^| bb | a') end)
  press('<<')
  wait('column back', function() return line(1):find('^| a') end)
  press('<Leader>oJ')
  wait('row down', function() return line(4):find('^| 1') end)
  press('<Leader>oK')
  wait('row up', function() return line(3):find('^| 1') end)
  press('>s')
  wait('column inserted', function() return line(1):find('^|%s+| a') or line(1):find('^| a |%s+|') or select(2, line(1):gsub('|', '')) == 4 end)
  H.out('  after >s: ' .. line(1))
  press('<s')
  wait('column deleted', function() return select(2, line(1):gsub('|', '')) == 3 end)
  press('<Leader>oTO')
  wait('row inserted above', function() return line(3):find('^|%s+|%s+|$') end)
  press('<Leader>oTd')
  wait('row deleted', function() return line(3):find('^| 1') end)
  press('<Leader>o-')
  wait('rule below', function() return line(4):find('^|%-') end)
  vim.api.nvim_win_set_cursor(0, { 4, 0 })
  press('dd')
  vim.api.nvim_win_set_cursor(0, { 3, 2 })
  press('<Leader>o<CR>')
  wait('rule and move below', function() return line(4):find('^|%-') and H.cursor()[1] == 5 end)
  H.out('  after o<CR>: ' .. vim.inspect(lines()) .. ' cursor ' .. vim.inspect(H.cursor()))
  vim.api.nvim_win_set_cursor(0, { 3, 2 })
  press('<Leader>o<Space>')
  wait('field blanked', function() return line(3):find('^|%s+|%s+2 |') end)
  H.out('  blanked: ' .. vim.inspect(lines()))
  -- sort rows by column
  H.open(dir .. '/s.org', { '| c | 3 |', '| a | 1 |', '| b | 2 |' })
  vim.api.nvim_win_set_cursor(0, { 1, 2 })
  H.keys({ 'a' })
  press('<Leader>o^')
  wait('rows sorted', function() return line(1) == '| a | 1 |' and line(3) == '| c | 3 |' end)
  -- shrink column
  H.open(dir .. '/w.org', { '| <5>         |', '| abcdefghijk |' })
  vim.api.nvim_win_set_cursor(0, { 2, 2 })
  press('<Leader>o<Tab>')
  H.sleep(800)
  local marks = vim.api.nvim_buf_get_extmarks(0, -1, 0, -1, { details = true })
  local shown = {}
  for _, m in ipairs(marks) do
    if m[4].virt_text then table.insert(shown, m[2] .. ':' .. table.concat(vim.tbl_map(function(c) return c[1] end, m[4].virt_text), '')) end
    if m[4].conceal then table.insert(shown, m[2] .. ':conceal' .. m[4].conceal) end
  end
  H.out('  shrunk: ' .. vim.inspect(shown))
  check(vim.iter(shown):any(function(s) return s:find('…') end), 'shrunk to 5 characters and …')
  -- copy down, sum, field info, create (Emacs)
  H.open(dir .. '/e.org', { '| n | v |', '|---+---|', '| 1 | 2 |', '|   |   |', '', 'off table' })
  vim.api.nvim_win_set_cursor(0, { 3, 2 })
  press('<Leader>oD')
  wait('copied down incremented', function() return line(4):find('^| 2') end, 15000)
  local n = #H.notes
  vim.api.nvim_win_set_cursor(0, { 3, 6 })
  press('<Leader>o+')
  H.wait(nil, function() return #H.notes > n end, 15000)
  H.out('  sum: ' .. vim.inspect(H.notes_since(n)))
  check(H.note_seen('Sum of', n), 'sum message')
  n = #H.notes
  press('<Leader>o?')
  H.wait(nil, function() return #H.notes > n end, 15000)
  H.out('  field info: ' .. vim.inspect(H.notes_since(n)))
  vim.api.nvim_win_set_cursor(0, { 6, 0 })
  press('<Leader>oD')
  H.sleep(800)
  H.out('  oD off table: ' .. vim.inspect(lines()))
  vim.api.nvim_win_set_cursor(0, { 5, 0 })
  H.inputs({ '3x2' })
  press('<Leader>oi<Bar>')
  wait('table created', function() return #lines() >= 9 end, 15000)
  H.out('  created: ' .. vim.inspect(lines()) .. ' asked ' .. vim.inspect(H.inputs_asked[#H.inputs_asked]))
end)

H.section('formulas', function()
  H.open(dir .. '/f.org', { '| 2 | 3 |   |', '| 4 | 5 |   |', '|   |   |   |', '#+TBLFM: $3=$1*$2::@3$2=vsum(@1..@2);%.2f' })
  vim.api.nvim_win_set_cursor(0, { 1, 2 })
  press('<Leader>o*')
  wait('recalculated', function() return line(1):find('|%s+6 |') and line(2):find('|%s+20 |') end, 15000)
  H.out('  tbl: ' .. vim.inspect(lines()))
  check(line(3):find('8%.00'), 'vsum with format')
  vim.api.nvim_buf_set_lines(0, 0, 1, false, { '| 3 | 3 | 6 |' })
  vim.api.nvim_win_set_cursor(0, { 1, 2 })
  vim.cmd('Org table recalculate line')
  wait('line recalculated', function() return line(1):find('|%s+9 |') end, 15000)
  vim.api.nvim_win_set_cursor(0, { 4, 3 })
  press('<C-Space>')
  H.sleep(1500)
  H.out('  C-c C-c on TBLFM: ' .. vim.inspect(lines()))
  vim.cmd('Org table iterate')
  H.sleep(2000)
  -- dates
  H.open(dir .. '/d.org', { '| <2026-10-21 Wed> |   |', '#+TBLFM: $2=$1+7' })
  press('<Leader>o*')
  wait('date arithmetic', function() return line(1):find('2026%-10%-28') end, 15000)
  -- elisp formula
  H.open(dir .. '/el.org', { '| 1 | 2 |   |', "#+TBLFM: $3='(+ $1 $2);N" })
  press('<Leader>o*')
  wait('elisp formula', function() return line(1):find('| 3 |$') or line(1):find('|%s+3%s+|$') end, 20000)
  H.out('  elisp: ' .. vim.inspect(lines()))
end)

H.section('babel', function()
  H.open(dir .. '/b.org', { '* Code', '#+NAME: hello', '#+begin_src emacs-lisp', '(+ 1 2)', '#+end_src', '', 'Inline src_emacs-lisp{(* 6 7)} here.', '', '#+begin_src sh :tangle out/x.sh :mkdirp yes :shebang #!/bin/sh', 'echo hi', '#+end_src' })
  vim.api.nvim_win_set_cursor(0, { 4, 0 })
  H.selects({ 'Yes' })
  local n = #H.notes
  press('<Leader>obe')
  wait('results', function() return has('^#%+RESULTS:') end, 20000)
  H.out('  after obe: ' .. vim.inspect(lines()) .. ' asked ' .. vim.inspect(H.inputs_asked[#H.inputs_asked]) .. vim.inspect(H.key_prompts[#H.key_prompts]))
  check(has('^: 3$'), 'result 3')
  press('<Leader>obk')
  wait('results removed', function() return not has('^#%+RESULTS:') end, 10000)
  -- C-c C-c in block
  H.selects({ 'Yes' })
  vim.api.nvim_win_set_cursor(0, { 4, 0 })
  press('<C-Space>')
  wait('results via C-c C-c', function() return has('^: 3$') end, 20000)
  -- inline
  local r
  for i, l in ipairs(lines()) do if l:find('src_emacs') then r = i end end
  vim.api.nvim_win_set_cursor(0, { r, 10 })
  H.selects({ 'Yes' })
  press('<Leader>obe')
  wait('inline result', function() return line(r):find('{{{results%(=42=%)}}}') end, 20000)
  -- tangle
  press('<Leader>obt')
  wait('tangled', function() return vim.fn.filereadable(dir .. '/out/x.sh') == 1 end, 15000)
  H.out('  tangled: ' .. vim.inspect(vim.fn.readfile(dir .. '/out/x.sh')) .. ' exec ' .. vim.fn.executable(dir .. '/out/x.sh') .. ' notes ' .. vim.inspect(H.notes_since(n)))
  eq(vim.fn.readfile(dir .. '/out/x.sh')[1], '#!/bin/sh', 'shebang')
  -- next/previous block, goto named
  vim.api.nvim_win_set_cursor(0, { 1, 0 })
  press('<Leader>obn')
  wait('next block', function() return line(H.cursor()[1]):find('^#%+begin_src') end, 10000)
  H.selects({ 'hello' })
  H.inputs({ 'hello' })
  vim.api.nvim_win_set_cursor(0, { 1, 0 })
  press('<Leader>obg')
  H.sleep(3000)
  H.out('  goto named: ' .. vim.inspect(H.cursor()) .. ' ' .. tostring(line(H.cursor()[1])))
  -- edit special
  vim.api.nvim_win_set_cursor(0, { 4, 0 })
  press("<Leader>o'")
  wait('edit buffer', function() return vim.api.nvim_buf_get_name(0):find('%.el$') end, 15000)
  H.out('  edit special: ' .. vim.api.nvim_buf_get_name(0) .. ' ' .. vim.inspect(lines()))
  vim.api.nvim_buf_set_lines(0, 0, -1, false, { '(+ 1 2 3)' })
  vim.cmd('write')
  wait('written back', function() return has('^%s*%(%+ 1 2 3%)$', vim.fn.bufnr(dir .. '/b.org')) end, 10000)
end)

H.section('export', function()
  H.open(dir .. '/x.org', { '#+TITLE: Ex', '* One', 'text one', '* Two', 'unsaved' })
  vim.api.nvim_buf_set_lines(0, 4, 5, false, { 'unsaved change' })
  local opened = {}
  local ui_open = vim.ui.open
  vim.ui.open = function(u) table.insert(opened, u) return nil, nil end
  H.keys({ 'h', 'h' })
  local n = #H.notes
  press('<Leader>oe')
  wait('html written', function() return vim.fn.filereadable(dir .. '/x.html') == 1 end, 30000)
  H.out('  export menu: ' .. vim.inspect(H.key_prompts[#H.key_prompts - 1]) .. ' notes ' .. vim.inspect(H.notes_since(n)))
  local html = table.concat(vim.fn.readfile(dir .. '/x.html'), '\n')
  check(html:find('unsaved change', 1, true) ~= nil, 'unsaved changes in the export')
  check(not html:find('table%-of%-contents'), 'org-export-with-toc false from emacs_options: no TOC')
  -- subtree as UTF-8 text in a buffer
  vim.api.nvim_win_set_cursor(0, { 3, 0 })
  H.keys({ '\19', 't', 'U' })
  press('<Leader>oe')
  H.sleep(8000)
  H.out('  text export: ' .. vim.api.nvim_buf_get_name(0) .. ' ' .. vim.inspect(vim.list_slice(lines(), 1, 8)))
  vim.ui.open = ui_open
end)

H.section('attach mv (emacs_options)', function()
  local src = dir .. '/to-attach.txt'
  vim.fn.writefile({ 'attach me' }, src)
  H.open(dir .. '/a.org', { '* Entry' })
  H.keys({ 'a' })
  H.inputs({ src })
  local n = #H.notes
  press('<Leader>oxa')
  wait('attached', function() return has(':ID:') and line(1):find(':ATTACH:') end, 20000)
  H.out('  attach: ' .. vim.inspect(lines()) .. ' notes ' .. vim.inspect(H.notes_since(n)) .. ' asked ' .. vim.inspect(H.key_prompts[#H.key_prompts]) .. vim.inspect(H.inputs_asked[#H.inputs_asked]))
  eq(vim.fn.filereadable(src), 0, 'mv: the source file is gone')
  local found = vim.fn.globpath(dir .. '/data', '**/to-attach.txt', 0, 1)
  check(#found == 1, 'the file is in the attachment directory: ' .. vim.inspect(found))
end)

H.section('timers', function()
  H.open(dir .. '/tm.org', { '* Timer', '' })
  local n = #H.notes
  press('<Leader>ox0')
  H.wait(nil, function() return #H.notes > n end, 15000)
  H.out('  timer start: ' .. vim.inspect(H.notes_since(n)) .. ' status ' .. H.plugin.clock_status())
  vim.api.nvim_win_set_cursor(0, { 2, 0 })
  press('<Leader>ox.')
  wait('timer value', function() return line(2):find('%d:%d%d:%d%d') end, 10000)
  press('o<Esc>')
  press('<Leader>ox-')
  wait('timer item', function() return has('^%- %d:%d%d:%d%d :: ') end, 10000)
  press('<Leader>ox,')
  H.sleep(1500)
  press('<Leader>ox_')
  H.sleep(1500)
  H.out('  timer notes: ' .. vim.inspect(H.notes_since(n)) .. ' lines ' .. vim.inspect(lines()))
end)

H.done()
