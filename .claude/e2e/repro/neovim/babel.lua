local H = dofile('/home/user/org-lsp/.claude/e2e/repro/neovim/h.lua')
local dir = H.tmpdir('babel')
H.init({ settings = {} })
H.section('babel prompt', function()
  H.open(dir .. '/b.org', { '* Code', '#+NAME: hello', '#+begin_src emacs-lisp', '(+ 1 2)', '#+end_src', '' })
  vim.api.nvim_win_set_cursor(0, { 4, 0 })
  H.selects({ 'yes' }); H.keys({ 'y' }); H.inputs({ 'yes' })
  press = H.press
  press('<Leader>obe')
  H.wait('results', function() return vim.iter(H.lines()):any(function(l) return l == ': 3' end) end, 20000)
  H.out('  asked: select ' .. vim.inspect(H.select_asked) .. ' keys ' .. vim.inspect(H.key_prompts) .. ' inputs ' .. vim.inspect(H.inputs_asked))
  H.out('  ' .. vim.inspect(H.lines()))
  vim.api.nvim_win_set_cursor(0, { 4, 0 })
  press("<Leader>o'")
  H.wait('edit buffer', function() return vim.api.nvim_buf_get_name(0):find('%.el$') end, 15000)
  local eb = vim.api.nvim_get_current_buf()
  vim.api.nvim_buf_set_lines(0, 0, -1, false, { '(+ 1 2 3)' })
  vim.cmd('write')
  H.sleep(3000)
  local ob = vim.fn.bufnr(dir .. '/b.org')
  H.out('  after write: org buf ' .. vim.inspect(H.lines(ob)) .. ' modified ' .. tostring(vim.bo[ob].modified) .. ' disk ' .. vim.inspect(vim.fn.readfile(dir .. '/b.org')) .. ' cur ' .. vim.api.nvim_buf_get_name(0))
  H.out('  notes ' .. vim.inspect(H.notes))
end)
H.done()
