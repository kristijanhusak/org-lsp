local H = dofile('/home/user/org-lsp/.claude/e2e/repro/neovim/h.lua')
local dir = H.tmpdir('dot')
H.init({ settings = { org_todo_keywords = { 'TODO(t)', '|', 'DONE(d)' } } })
H.section('dot', function()
  H.open(dir .. '/t1c.org', { '* P [0/2]', '** TODO c1', '** TODO c2', '** TODO c3' })
  vim.api.nvim_win_set_cursor(0, { 2, 0 })
  H.keys({ 'd', 'd', 'd' })
  H.press('cit')
  H.wait('cit', function() return H.line(2) == '** DONE c1' end)
  vim.api.nvim_win_set_cursor(0, { 3, 0 })
  H.press('.')
  H.wait('. repeats', function() return H.line(3) == '** DONE c2' end)
  H.out(vim.inspect(H.lines()) .. ' prompts ' .. #H.key_prompts)
  -- with the real main loop: the key typed through feedkeys without x
  vim.api.nvim_win_set_cursor(0, { 4, 0 })
  vim.api.nvim_feedkeys('.', 'm', false)
  H.wait('. repeats via main loop', function() return H.line(4) == '** DONE c3' end)
  H.out(vim.inspect(H.lines()) .. ' prompts ' .. #H.key_prompts .. ' op=' .. vim.o.operatorfunc)
end)
H.done()
