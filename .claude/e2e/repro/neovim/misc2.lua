local H = dofile('/home/user/org-lsp/.claude/e2e/repro/neovim/h.lua')
local dir = H.tmpdir('misc2')
H.init({ settings = { clock = { today = '2026-10-21', now = '10:30' },
  org_capture_templates = { { key = 'e', description = 'Elisp', target = { 'file', dir .. '/inbox.org' }, template = '* %(upcase "abc")' } } } })
H.section('archive sibling', function()
  H.open(dir .. '/s.org', { '* Inbox', '* Done two', 'body', '* Archive :ARCHIVE:', '** older' })
  vim.api.nvim_win_set_cursor(0, { 2, 0 })
  H.press('<Leader>oxA')
  H.sleep(2500)
  H.out('  after oxA: ' .. vim.inspect(H.lines()) .. ' notes ' .. vim.inspect(H.notes))
  H.open(dir .. '/s2.org', { '* Inbox', '* Done two', 'body' })
  vim.api.nvim_win_set_cursor(0, { 2, 0 })
  H.press('<Leader>oxA')
  H.sleep(2500)
  H.out('  after oxA (no sibling yet): ' .. vim.inspect(H.lines()))
end)
H.section('footnote back', function()
  H.open(dir .. '/f.org', { '* A', 'Text [fn:1] here.', '* Footnotes', '[fn:1] One.' })
  vim.api.nvim_win_set_cursor(0, { 2, 6 })
  H.press('<Leader>oo')
  H.sleep(800)
  H.out('  at def: ' .. vim.inspect(H.cursor()))
  H.press('<Leader>oo')
  H.sleep(800)
  H.out('  back: ' .. vim.inspect(H.cursor()) .. ' notes ' .. vim.inspect(H.notes))
  vim.api.nvim_win_set_cursor(0, { 4, 2 })
  H.press('<Leader>oo')
  H.sleep(800)
  H.out('  from inside label: ' .. vim.inspect(H.cursor()))
  vim.api.nvim_win_set_cursor(0, { 4, 0 })
  H.press('<Leader>of')
  H.sleep(1500)
  H.out('  of on def: ' .. vim.inspect(H.cursor()))
end)
H.section('capture elisp', function()
  H.keys({ 'e' })
  H.press('<Leader>oc')
  H.wait('capture', function() return vim.fs.basename(vim.api.nvim_buf_get_name(0)):find('^CAPTURE') end, 20000)
  H.out('  elisp capture: ' .. vim.inspect(H.lines()))
  H.check(H.line(1) == '* ABC', '%(upcase "abc")')
end)
H.done()
